// Writes src/core/migrations-sql.ts from migrations/0001_init.sql so MIGRATIONS_SQL byte-equals the file (PRD 11.5).
import { readFileSync, writeFileSync } from "node:fs";
const sql = readFileSync(new URL("../migrations/0001_init.sql", import.meta.url), "utf8");
const out = `// GENERATED by scripts/gen-migrations.mjs from migrations/0001_init.sql. Do not edit.\nexport const MIGRATIONS_SQL: string = ${JSON.stringify(sql)};\n`;
writeFileSync(new URL("../src/core/migrations-sql.ts", import.meta.url), out);
